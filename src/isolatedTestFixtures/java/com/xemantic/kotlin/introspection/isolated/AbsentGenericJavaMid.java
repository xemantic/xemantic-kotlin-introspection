package com.xemantic.kotlin.introspection.isolated;

/**
 * A generic Java class extending {@link Absent}, so that it cannot be loaded without it,
 * while its class file can still be read.
 */
public abstract class AbsentGenericJavaMid<T> extends Absent implements Comparable<T> {

    public void process(T item) {
    }

    public void run() {
    }

    public final void finish() {
    }

}
