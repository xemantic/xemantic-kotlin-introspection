package com.xemantic.kotlin.introspection.isolated

// A nested class deprecated with the HIDDEN level, like the $serializer generated by kotlinx.serialization,
// whose class file a test does not serve as a resource, like an in-memory class loader might not.
class HiddenNestedHolder {
    class Visible
    @Deprecated("generated", level = DeprecationLevel.HIDDEN)
    object Hidden
}

// A deprecated nested class, and a companion object deprecated with the HIDDEN level,
// whose class files a test does not serve as resources, judged then by reflection.
class DeprecatedNestedHolder {
    @Deprecated("Old")
    class Old
    @Deprecated("generated", level = DeprecationLevel.HIDDEN)
    companion object {
        fun create(): DeprecatedNestedHolder = DeprecatedNestedHolder()
    }
}

// An open class whose only constructor is deprecated with the HIDDEN level, and a hidden function,
// whose class file a test does not serve as a resource, judged then by reflection,
// so that the user code cannot subclass it, nor use its protected members
open class HiddenConstructorBase @Deprecated("internal", level = DeprecationLevel.HIDDEN) constructor() {
    protected fun forSubclasses() {}
    @Deprecated("replaced", level = DeprecationLevel.HIDDEN)
    fun hiddenFunction() {}
    fun visible() {}
}
